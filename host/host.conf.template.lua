--     -- to make each logged line an average over exactly that interval.
--     profile_window_ms = 1000,
--
--     -- Cadence, in milliseconds, of a periodic profiler summary dumped
--     -- to the log (stderr). 0 disables it; any other value is clamped
--     -- to 250..60000.
--     profile_log_ms = 0,
