-- glyphwire configuration template.
--
-- This is the full reference for `host.conf.lua`, the file glyphwire runs
-- once at startup (see host/main.zig `loadConfig`). Copy it to one of:
--
--   $GLYPHWIRE_CONFIG_DIR/host.conf.lua
--   $XDG_CONFIG_HOME/glyphwire/host.conf.lua
--   ~/.config/glyphwire/host.conf.lua                  (the usual location)
--
-- Every option is listed below at its built-in default, with every line
-- commented out -- so copying this file verbatim changes nothing.
-- Uncomment and edit only the keys you want to override; a missing file
-- (or no config directory at all), or a `config` table missing a key,
-- keeps that key's default.
--
-- Syntax: it's a plain Lua script. Assign a single global table named
-- `config`. Values are Lua literals -- strings in quotes, numbers bare,
-- booleans `true` / `false`. `--` starts a comment. Unknown keys are
-- ignored. A key set to the wrong type logs a warning and the default
-- stands.
--
-- Custom icons: drop `.png` files into an `icons/` subdirectory of this
-- config directory (e.g. ~/.config/glyphwire/icons/). Each is registered
-- under its path there without the extension, so
-- icons/mine/logo.png -> the name `mine/logo`, and a file at a bundled
-- path such as icons/file/folder.png replaces that bundled icon. Use
-- the name in a prompt `{icon:...}`, a client's `draw_icon`, etc.

