--     -- The chord that opens the theme switcher: every built-in theme
--     -- and every `themes` entry in theme.lua. Moving the selection
--     -- previews it on the whole window; Enter keeps it, Escape puts
--     -- back the one you started with. Only for this session -- theme.lua
--     -- still decides the next one. A program whose own config names a
--     -- `theme` keeps it. Same chord syntax as above; false turns it off.
--     theme_switcher_key = "super+f10",
--
--     ---- Pane dividers ----------------------------------------------
--
--     -- How the lines between panes (gmux splits) are drawn, in the
--     -- theme's `pane_divider` colour: "single" (─ │ with ├ ┤ ┬ ┴ ┼
--     -- where they meet), "heavy" (━ ┃ ╋), "double" (═ ║ ╬), or "block"
--     -- (a solid band). The bands inside a program (zoe's tree|editor
--     -- line, salacommander's middle) use it too, in the dimmer
--     -- `divider` colour, unless that program's own config sets
--     -- `divider_style` / `divider_chars`.
--     pane_divider_style = "single",
--
--     -- Override any of the style's glyphs, each one cell wide. Keys:
--     -- h, v, cross, t_down (┬), t_up (┴), t_left (┤), t_right (├),
--     -- tl (┌), tr (┐), bl (└), br (┘). Any subset; with "block" the
--     -- rest come from "single".
--     pane_divider_chars = { h = "─", v = "│" },
--
--     -- How strongly a drag's drop target is highlighted (zoe's tab
--     -- moving onto another pane, say): the pane or cells it would land
--     -- on are washed in the theme's `drop_target` colour at this
--     -- opacity. The insertion bar between two tabs is always solid.
--     -- Clamped to 0.05..1.
--     drop_target_opacity = 0.25,
--
--     -- The focused pane's highlight, drawn on the pane dividers around
--     -- it (so a lone pane, or a side at the window's edge, shows none):
--     -- "none", "solid" (pane_focus_color held steady), or "pulse"
--     -- (eased to pane_focus_pulse_color and back, each way taking
--     -- pane_focus_pulse_seconds, clamped to 0.1..60). Colours are a
--     -- palette slot ("bright_blue"), a theme role ("accent"), or
--     -- "#rrggbb"; the defaults are the theme's `pane_focus` and
--     -- `pane_focus_pulse` roles. An unfocused window holds the first
--     -- colour still.
--     pane_focus_highlight = "pulse",
--     pane_focus_color = "pane_focus",
--     pane_focus_pulse_color = "pane_focus_pulse",
--     pane_focus_pulse_seconds = 1.5,
--
--     ---- Grid --------------------------------------------------------
--
--     -- Initial grid size in cells. The window opens this many cells
--     -- wide/tall (times the measured cell pixel size); after that it's
--     -- user-resizable and the grid tracks the window's live size.
--     -- Clamped up to 16 cols / 4 rows. A `--grid-cols` / `--grid-rows`
--     -- command-line flag overrides these.
--     grid_cols = 120,
--     grid_rows = 50,
--
--     -- Root layer scrollback depth, in rows: how many scrolled-off rows
--     -- the history ring keeps for the mouse wheel / scrollbar to reach.
--     -- Clamped to 0..100000.
--     scrollback_rows = 1000,
--
--     ---- Startup ----------------------------------------------------
--
--     -- What the window runs instead of the gw-shell prompt: a program
--     -- name ("gmux") or an argv list ({ "zoe", "notes.md" }). A lone
--     -- string is one program, never split on spaces, so put arguments
--     -- in the list form. It's started the same way `glyphwire gmux`
--     -- would be, so the window closes when it exits. A command given on
--     -- the command line (`glyphwire zoe`) wins over this, and `--ssh`
--     -- ignores it. Unset (the default) runs the shell's prompt.
--     default_program = "gmux",
--
--     ---- Icons ------------------------------------------------------
--
--     -- Which bundled file-type icon set backs the canonical `file/*`
--     -- names (folder, file, image, pdf, ...) that glyphwire-ls draws
--     -- with: "oxygen" (the default, KDE Oxygen), "material" (the VS Code
--     -- Material Icon Theme), or "papirus". An unknown name, or a theme
--     -- whose icons aren't present, warns and falls back to "oxygen".
--     -- Language / tool logos (dev/zig, distro/arch, ...) are the same in
--     -- every theme.
--     icon_theme = "oxygen",
--
--     ---- Profiler ---------------------------------------------------
--
--     -- Frame-timing profiler. When off (the default) every measurement
--     -- call is a cheap early-return, so the idle redraw-on-demand path
--     -- costs nothing. When on, per-phase timings (wait, update,
--     -- sync_batches, draw, present, ...) and volume counters (layers
--     -- rebuilt, draw calls, quads) are collected and reachable over the
--     -- wire as `get_property "profile"`.
--     profile = false,
--
--     -- Whether the on-screen profiler HUD starts visible.
--     -- Ctrl+Alt+Shift+P toggles it while `profile` is true. The HUD
--     -- forces a repaint every frame while shown (bounded to ~10 Hz), so
--     -- leave it off until you want to watch the numbers.
--     profile_hud = false,
--
--     -- Start with forced every-frame redraw: the host repaints every
--     -- frame instead of only on a change, the way it did before the
--     -- redraw-on-demand work. For measuring steady-state draw cost and
--     -- A/B-ing it against the idle path. Ctrl+Alt+Shift+R toggles it
--     -- while `profile` is true.
--     profile_force_redraw = false,
--
--     -- Averaging window in milliseconds. Every profiler number (phase
--     -- avg/p95/max, per-frame counter means, fps) is accumulated over
