--     -- Primary font. Any of:
--     --   * a bare name -> the bundled asset of that name, resolved under
--     --     GLYPHWIRE_ASSET_DIR when set, otherwise under
--     --     ../share/glyphwire/assets relative to the glyphwire executable;
--     --   * an absolute or cwd-relative path to a TTF/OTF/TTC file;
--     --   * a system font family name ("DejaVu Sans Mono", "Fira Code")
--     --     or a fontconfig generic ("monospace") -- looked up with
--     --     `fc-match`, so fontconfig has to be installed.
--     -- A name that matches none of these warns and the bundled default
--     -- is used. For a TTC, also set `font_face_name` (a system TTC uses
--     -- the face fc-match picked unless you do).
--     font_face = "NotoSansCJK-Regular.ttc",
--
--     -- For a TTC: a substring of the desired face's name
--     -- (case-sensitive). Ignored for a plain TTF/OTF. Falls back to
--     -- face 0 if no name matches.
--     font_face_name = "Mono CJK JP",
--
--     -- Faces tried for any codepoint the primary font lacks, before the
--     -- atlas falls back to its .notdef (tofu) box. One font, or a list
--     -- tried in order. Same accepted forms as `font_face` (bundled
--     -- name, path, or system family name). One that can't be found is
--     -- skipped with a warning.
