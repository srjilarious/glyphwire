-- gmux configuration template.
--
-- This is the full reference for `gmux.conf.lua`, the file gmux runs once at
-- startup (see gmux/config.zig `load`). Copy it to one of:
--
--   $GLYPHWIRE_CONFIG_DIR/gmux.conf.lua
--   $XDG_CONFIG_HOME/glyphwire/gmux.conf.lua
--   ~/.config/glyphwire/gmux.conf.lua                   (the usual location)
--
-- Every key is listed below at its built-in default, with every line
-- commented out -- so copying this file verbatim changes nothing.
-- Uncomment and edit only the keys you want to override. With no file at
-- all gmux uses Ctrl-B as the prefix, gw-shell for every pane, and a
-- 2000-row scrollback ring per pane.
--
-- Syntax: a plain Lua script (standard libraries open). Assign a single
-- global table named `config`. Unknown keys are ignored; a key of the
-- wrong type is logged and the default stands. Any parse error is logged
-- and whatever parsed before it is kept.
--
-- Scrollback style and the starting pane layout are not configurable
-- yet. How the lines between panes
-- look is the host's to draw: see `pane_divider_style` in host.conf.lua.

-- config = {
--
--     -- The letter after Ctrl that starts a command (screen-style
--     -- Ctrl-A, tmux-style Ctrl-B, ...). One lowercase ASCII letter.
--     -- After it: " splits the focused pane below, % splits it to the
--     -- right, an arrow key moves focus in that direction, x kills the
--     -- focused pane, z toggles zooming it to fill the window (any
--     -- other command un-zooms first, then acts), } and { rotate every
--     -- pane one slot forward/back through the layout (focus stays on
--     -- the slot, and a zoom stays on, showing the pane that rotated
--     -- in), H/L shrink/grow the focused pane along a row-axis
--     -- split, J/K along a column-axis one, q quits
--     -- gmux, P opens the command palette (every command, searchable,
--     -- with its keys), m starts layout mode (drag a pane onto
--     -- another's edge to move it there, onto its middle to swap the
--     -- two, or onto a window edge for a full-height column or
--     -- full-width row; Esc or Enter finishes), and the prefix again
--     -- (Ctrl-B Ctrl-B) sends one Ctrl-B on to the focused program --
--     -- zoe's sidebar toggle, say.
--     prefix_key = "b",
--
--     -- The command run in a fresh pane, overriding the default
--     -- gw-shell. No arguments -- just the program itself, same as
--     -- opening a new terminal window. Any ordinary shell (bash, fish,
--     -- ...) works fine here: a pane is a sequestered host, so a plain
--     -- program gets a real pty and a terminal of exactly the pane's
--     -- size. gw-shell is the better default only because a
--     -- glyphwire-aware program draws on the pane's own context rather
--     -- than through VT emulation.
--     shell = "/bin/bash",
--
--     -- How many rows of scrollback a fresh pane keeps -- its own ring,
--     -- scrolled with the mouse wheel over that pane, independent of
--     -- every other pane's.
--     scrollback_rows = 2000,
--
--     -- Rebinds the commands after the prefix, by name, over the
--     -- defaults; `false` takes one away. A punctuation character or an
--     -- uppercase letter is that character as your keyboard layout
--     -- types it; a lowercase letter or digit is read off what you type
--     -- too; anything else is a key chord ("left", "ctrl+x").
--     --
--     --   focusLeft left, focusRight right, focusUp up, focusDown down,
--     --   splitBelow ", splitRight %, killPane x, zoom z,
--     --   resizeLeft H, resizeRight L, resizeUp K, resizeDown J,
--     --   rotateForward }, rotateBackward {, quit q,
--     --   commandPalette P, layoutMode m,
--     --   sendPrefix ctrl+<prefix_key>
--     keys = {
--         -- ["-"] = "splitBelow", ["|"] = "splitRight",
--     },
-- }
